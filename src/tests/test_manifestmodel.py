"""si#346: the bridge from a validated manifest to an M1 `.firn` model. Pure: no docker, no firn.

DEMO is the brief's demo made loadable: the brief placed `test:typecheck-python` under `ci: build`, which
si#34 refuses at load, so the hyphenated command here binds `build:nuget-config`, a coordinate the
catalogue allows under build. It loads with no cd group: the matrix alone is enough (measured).

AAA throughout.
"""
import pytest
import yaml

from simplon import catalogue, manifestmodel
from simplon.orchestrator import manifest as manifest_mod

DEMO = """\
product: demo
ci:
  build:
    commands:
      image: { task: "build:image" }
      nuget-config: { task: "build:nuget-config" }
      all: { depends_on: [image], help: "Build everything." }
cd:
  default: dev
  environments:
    dev: {}
    prod: {}
images:
  kernel: { registry: ghcr.io/x, repository: demo, dockerfile: Dockerfile, context: . }
jdk:
  version: 21
"""


def _load(text: str = DEMO) -> manifest_mod.Manifest:
    return manifest_mod.load(text, catalogue=catalogue.load())


def _export(text: str = DEMO) -> str:
    return manifestmodel.export(_load(text), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)


def _block(out: str, head: str) -> str:
    """The body of the block `head` opens, up to its first closing brace."""
    return out.split(head, 1)[1].split("}", 1)[0]


@pytest.mark.parametrize("raw, mangled", [
    ("typecheck-python", "typecheck_python"), ("build:image", "build_image"),
    ("simplon.tasks.image:build", "simplon_tasks_image_build"), ("7zip", "_7zip"), ("ok_1", "ok_1")])
def test_mangle_makes_a_firn_name(raw, mangled):
    assert manifestmodel.mangle(raw) == mangled


def test_the_export_is_one_product_in_its_own_package():
    # act
    out = _export()

    # assert
    assert out.startswith("// GENERATED by `support manifest model`")
    assert "package product.demo\n" in out
    assert "demo typeOf simplon.manifest.Product {" in out
    assert out.count("{") == out.count("}")


def test_a_name_that_is_not_a_firn_name_keeps_its_original_in_key():
    # act
    out = _export()

    # assert
    assert 'key = "nuget-config"' in _block(out, "command nuget_config typeOf simplon.pipeline.TaskCommand {")


def test_a_command_runs_the_task_named_by_its_measured_impl():
    # arrange: `build:image` resolves to this impl in today's catalogue (measured, not assumed)
    assert _load().spec_for("build", "image").impl == "simplon.tasks.image:build"

    # act
    out = _export()

    # assert
    assert "task = product.demo.demo.t_simplon_tasks_image_build" in _block(
        out, "command image typeOf simplon.pipeline.TaskCommand {")
    task = _block(out, "tasks t_simplon_tasks_image_build typeOf simplon.pipeline.Task {")
    assert 'key = "simplon.tasks.image:build"' in task and 'body = "simplon.tasks.image:build"' in task


def test_an_aggregate_names_its_members_and_runs_no_task():
    # act
    block = _block(_export(), "command all typeOf simplon.pipeline.AggregateCommand {")

    # assert
    assert "member = product.demo.demo.build.image" in block
    assert "task =" not in block


def test_a_group_stands_under_its_area_and_support_is_an_area_too():
    # act
    out = _export()

    # assert: area_of says None for support; the model says support
    assert "area = simplon.pipeline.Area.ci" in _block(out, "ci build typeOf simplon.pipeline.Group {")
    assert "area = simplon.pipeline.Area.support" in _block(out, "support support typeOf simplon.pipeline.Group {")


def test_a_nested_group_nests_as_a_group_composition():
    # act
    out = _export()
    support = out.split("support support typeOf simplon.pipeline.Group {", 1)[1]

    # assert: `support.git` is `group git` INSIDE support, and its commands are addressed through it
    assert "group git typeOf simplon.pipeline.Group {" in support
    assert "group git typeOf" not in out.split("support support typeOf", 1)[0]


def test_environments_follow_the_matrix_and_promote_in_order():
    # act
    out = _export()

    # assert
    dev = _block(out, "environments e_dev typeOf simplon.pipeline.Environment {")
    assert 'key = "dev"' in dev and "next = product.demo.demo.e_prod" in dev
    assert "next =" not in _block(out, "environments e_prod typeOf simplon.pipeline.Environment {")


def test_an_image_is_an_artifact_of_the_image_kind():
    # act
    block = _block(_export(), "images i_kernel typeOf simplon.pipeline.Artifact {")

    # assert
    assert 'key = "kernel"' in block and "kind = simplon.vocabulary.image" in block


def test_an_artifacts_entry_is_an_artifact_of_the_artifact_kind():
    # arrange
    text = DEMO + "artifacts:\n  updatesite: { path: build/site }\n"

    # act
    block = _block(manifestmodel.export(_load(DEMO), yaml.safe_load(text), "demo",
                                        manifestmodel.KERNEL_SECTIONS),
                   "artifacts a_updatesite typeOf simplon.pipeline.Artifact {")

    # assert
    assert 'key = "updatesite"' in block and "kind = simplon.vocabulary.artifact" in block


def test_a_product_section_is_opaque_product_data():
    # act
    block = _block(_export(), "data d_jdk typeOf simplon.manifest.ProductData {")

    # assert
    assert 'key = "jdk"' in block
    assert "21" not in block


def test_a_kernel_section_is_a_kernel_section_and_product_is_the_resource_itself():
    # arrange
    text = DEMO + "claude:\n  plugins: []\n"

    # act
    out = manifestmodel.export(_load(DEMO), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)

    # assert
    assert 'key = "claude"' in _block(out, "claude s_claude typeOf simplon.manifest.KernelSection {")
    assert 'key = "demo"' in _block(out, "demo typeOf simplon.manifest.Product {")
    assert '"product"' not in out and " product " not in out and "d_product" not in out


def test_a_group_and_a_section_of_one_name_are_two_resources():
    # arrange: cleon's `build:` section next to its `ci: build` group - firn gives one owner ONE
    # namespace whatever the property (measured: E001 "has 2 typeOf statements"), so the section is
    # prefixed the way a task is
    text = DEMO + "build:\n  heap: 2g\n"

    # act
    out = manifestmodel.export(_load(DEMO), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)

    # assert
    assert "ci build typeOf simplon.pipeline.Group {" in out
    assert "build s_build typeOf simplon.manifest.KernelSection {" in out


def test_names_that_mangle_alike_are_refused_naming_both():
    # arrange
    text = DEMO.replace("      all: {", "      nuget_config: { task: \"build:image\" }\n      all: {")

    # act / assert
    with pytest.raises(manifestmodel.ModelExportError) as e:
        _export(text)
    assert "'nuget-config'" in str(e.value) and "'nuget_config'" in str(e.value)


def test_the_guard_holds_the_owner_not_the_property():
    # arrange: two different properties of one Product, one mangled name
    text = DEMO + "x-y: 1\nx_y: 2\n"

    # act / assert
    with pytest.raises(manifestmodel.ModelExportError, match=r"'x-y' and 'x_y' are both 'd_x_y'"):
        manifestmodel.export(_load(DEMO), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)


def test_a_member_that_resolves_nowhere_is_refused():
    # arrange: load() cannot produce this, so the manifest is edited after it
    mf = _load()
    spec = mf.commands["build"]["all"]._replace(depends_on=("nowhere",))
    mf = mf._replace(commands={**mf.commands, "build": {**mf.commands["build"], "all": spec}})

    # act / assert
    with pytest.raises(manifestmodel.ModelExportError, match="'nowhere'"):
        manifestmodel.export(mf, yaml.safe_load(DEMO), "demo", manifestmodel.KERNEL_SECTIONS)


def test_a_string_is_quoted_with_its_quote_and_backslash_escaped():
    # arrange
    text = DEMO + "'a\"b\\c': 1\n"

    # act
    out = manifestmodel.export(_load(DEMO), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)

    # assert
    assert 'key = "a\\"b\\\\c"' in out


def test_the_guard_refuses_one_original_named_twice_in_one_owner():
    # arrange: what a group `build` and a section `build` would be without their prefixes (cleon, swi);
    # a guard comparing only originals let it through, and firn answered E001
    names = manifestmodel._Names("product 'demo'")
    names("build")

    # act / assert
    with pytest.raises(manifestmodel.ModelExportError, match="'build' and 'build' are both 'build'"):
        names("build")
