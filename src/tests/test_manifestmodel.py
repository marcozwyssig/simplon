def _load(text: str = DEMO) -> manifest_mod.Manifest:
    return manifest_mod.load(text, catalogue=catalogue.load())


def _export(text: str = DEMO) -> str:
    return manifestmodel.export(_load(text), yaml.safe_load(text), "demo", manifestmodel.KERNEL_SECTIONS)


def _block(out: str, head: str) -> str:
    """The body of the block `head` opens, up to its first closing brace."""
    return out.split(head, 1)[1].split("}", 1)[0]


