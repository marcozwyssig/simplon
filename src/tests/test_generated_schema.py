"""si#344 B2: the artifact schema is a WHOLE module firn writes, and firn v0.1.0 loses output with rc 0.

Measured on v0.1.0 (B1, 2026-10-12): a selector that answers nothing deletes a generated file with rc 0
(firn#966), and a template error leaves a file holding only the id line. This file has no protected region,
so nothing in it survives a bad run - which is why every property of it is pinned here, on the committed
file, without docker.

AAA; the name states the behaviour under test.
"""
import re
from pathlib import Path

import pytest
from pydantic import ValidationError

from simplon import artifactschema, catalogue

MODULE = Path(artifactschema.__file__)
KINDS_MODEL = Path(__file__).resolve().parents[1] / "firn" / "model" / "simplon" / "vocabulary" / "kinds.firn"
SHAPES = {"text", "texts", "table", "untyped"}


def _model_kinds() -> set[str]:
    names = re.findall(r"^(\w+) typeOf simplon\.pipeline\.ArtifactKind", KINDS_MODEL.read_text(), re.M)
    assert names, "the model regex found no kinds - every test below would pass over nothing"
    return {name.replace("_", "-") for name in names}


def _class(kind: str) -> type:
    return type(artifactschema.validate(kind, {"kind": kind}))


def test_the_committed_module_is_whole_and_says_it_is_generated():
    # arrange
    lines = [line for line in MODULE.read_text(encoding="utf-8").splitlines() if line.strip()]

    # act
    code = [line for line in lines if not line.startswith("#")]

    # assert: more than firn's id line, which is all a template error leaves behind
    assert lines[0].startswith("# GENERATED from src/firn/model/simplon/vocabulary/kinds.firn")
    assert re.fullmatch(r"# Generated by firn\b.*\bid=\[ArtifactSchema:,\w+\]", lines[-1])
    assert len(code) > 20


def test_every_kind_in_the_model_has_a_model_class_of_that_kind():
    # arrange
    expected = _model_kinds()

    # act
    classes = {kind: _class(kind) for kind in artifactschema.REFINES}

    # assert: an empty selector leaves REFINES and the classes empty with rc 0
    assert set(artifactschema.REFINES) == expected
    assert {kind: cls.KIND for kind, cls in classes.items()} == {kind: kind for kind in expected}


def test_the_schema_and_the_catalogue_hold_the_same_kinds():
    # act / assert: both are generated from kinds.firn; they agree or one of them is stale
    assert artifactschema.REFINES == catalogue.load().kinds


def test_a_kind_that_refines_another_is_its_subclass():
    # act
    parents = {kind: (cls.__bases__[0].KIND if cls.__bases__[0] is not artifactschema.BaseModel else "")
               for kind, cls in ((kind, _class(kind)) for kind in artifactschema.REFINES)}

    # assert: `isinstance(entry, DirectoryEntry)` for a site is what "accepts every kind that refines it" rests on
    assert parents == artifactschema.REFINES


def test_every_field_has_a_shape_the_validator_rules_on():
    # act
    for kind in artifactschema.REFINES:
        cls = _class(kind)

        # assert: a shape `_typed` does not know would fall through to its mapping branch
        assert set(cls.SHAPES.values()) <= SHAPES, (kind, cls.SHAPES)
        assert set(cls.SHAPES) == set(cls.model_fields), (kind, sorted(cls.SHAPES), sorted(cls.model_fields))


def test_every_reader_names_a_catalogue_coordinate_a_kind_and_needs_of_that_kind():
    # arrange
    tasks = catalogue.load().tasks

    # act
    unknown = sorted(c for c in artifactschema.READERS if c not in tasks)
    stray = {c: [k for k in needs if k not in _class(artifactschema.READERS[c]).SHAPES]
             for c, needs in artifactschema.NEEDS.items()}

    # assert
    assert len(artifactschema.READERS) == 10
    assert unknown == []
    assert set(artifactschema.READERS.values()) <= set(artifactschema.REFINES)
    assert set(artifactschema.NEEDS) == set(artifactschema.READERS)
    assert all(artifactschema.NEEDS.values()), "a reader with no needs: a template that answered nothing"
    assert stray == {c: [] for c in artifactschema.NEEDS}


