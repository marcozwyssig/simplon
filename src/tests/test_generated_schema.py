@pytest.mark.parametrize("body,sentence", [
    ({"registry": ""}, "'registry' must be a non-empty string or a number"),
    ({"registry": True}, "'registry' must be a non-empty string or a number"),
    ({"registry": ["ghcr.io"]}, "'registry' must be a non-empty string or a number"),
    ({"tag": None}, "'tag' is written with no value - give it one, or delete the key"),
    ({"platforms": "linux/amd64"}, "'platforms' must be a list of non-empty strings, e.g. [a, b]"),
    ({"platforms": [7]}, "'platforms' must be a list of non-empty strings, e.g. [a, b]"),
    ({"build_args": ["A=1"]}, "'build_args' must be a mapping of name to value"),
    ({"build_args": {"A": [1]}}, "'build_args': 'A' must be a scalar, not list"),
    ({"platfroms": ["linux/amd64"]},
     "'platfroms' is not a key of a `image` artifact - did you mean 'platforms'?; it takes build_args, "
     "build_contexts, context, contexts, dockerfile, kind, local, name, path, platforms, registry, "
     "repository, tag"),
    ({"zzz": 1},
     "'zzz' is not a key of a `image` artifact; it takes build_args, build_contexts, context, contexts, "
     "dockerfile, kind, local, name, path, platforms, registry, repository, tag"),
])
def test_a_key_of_the_wrong_shape_or_name_is_refused_in_its_own_sentence(body, sentence):
    # act
    with pytest.raises(ValidationError) as caught:
        artifactschema.validate("image", {"kind": "image", **body})

    # assert: the sentence travels verbatim, which is what `artifactsection._validation_message` relies on
    assert str(caught.value.errors()[0]["ctx"]["error"]) == sentence


@pytest.mark.parametrize("kind", ["image", "maven", "nuget", "conan", "directory"])
def test_a_number_is_a_value_read_as_a_string(kind):
    # act: decision A - `tag: 25` loads, as `str(...)` in the readers always read it
    entry = artifactschema.validate(kind, {"kind": kind, "tag": 25, "registry": "ghcr.io/o"})

    # assert
    assert entry.tag == "25"


def test_an_unquoted_yaml_date_is_a_value_read_as_its_iso_text():
    # arrange: what `yaml.safe_load` gives for `tag: 2026-10-12` - a date, which `str(...)` always read as ISO text
    import yaml
    body = yaml.safe_load("kind: image\nregistry: ghcr.io/o\ntag: 2026-10-12\n")

    # act
    entry = artifactschema.validate("image", body)

    # assert
    assert entry.tag == "2026-10-12"


@pytest.mark.parametrize("value", [True, False])
def test_a_bool_is_still_not_a_text(value):
    # act / assert: the date opening is not a general scalar opening
    with pytest.raises(ValueError, match="'tag' must be a non-empty string or a number"):
        artifactschema.validate("image", {"kind": "image", "tag": value})


def test_a_present_value_is_read_into_its_shape_and_an_untyped_key_is_kept_as_written():
    # act
    entry = artifactschema.validate("image", {
        "kind": "image", "registry": " ghcr.io/o ", "platforms": ["linux/amd64", "linux/amd64 "],
        "build_args": {"A": 1, "B": True}, "name": {"product": "reads this"}, "tag": 1.0})

    # assert
    assert entry.registry == "ghcr.io/o"
    assert entry.platforms == ("linux/amd64",)
    assert entry.build_args == {"A": "1", "B": "true"}
    assert entry.name == {"product": "reads this"}
    assert entry.tag == "1.0"


def test_every_reader_in_the_model_is_a_coordinate_whose_body_reads_that_kind():
    # arrange: the catalogue maps a coordinate to its body; the body's module states the class it reads
    import importlib
    tasks = catalogue.load().tasks
    readers = {}
    for coordinate, spec in tasks.items():
        module = importlib.import_module(spec["impl"].split(":")[0])
        if getattr(module, "SECTION", None) == "artifacts" and hasattr(module, "ENTRY"):
            readers[coordinate] = module.ENTRY.KIND

    # act / assert: both directions - a reader the model lacks, and a model reader no body has
    assert readers == artifactschema.READERS
