"""simplon's own `whole-files` task (si#344 B2): the step after `firn gen` that refuses what firn#966 leaves.

firn v0.1.0 deletes every file a template no longer produces when a selector answers nothing, with rc 0,
and a template error leaves a file holding only firn's id line. `make-readable` already refuses a missing
file; nothing refused an id-line-only one - and `artifactschema.py` has no protected region to keep it
from being exactly that.

AAA; the name states the behaviour under test.
"""
import sys

import pytest

from conftest import ROOT  # noqa: E402 - the one product-root anchor (si#283)

sys.path.insert(0, str(ROOT / "deploy" / "orchestrator" / "src" / "python"))
from orchestrator import cli  # noqa: E402 - the product's own module, only reachable from here

GENERATED = ["src/simplon/catalogue.yaml", "src/site/content/with-what/kinds.md", "src/simplon/artifactschema.py",
             "src/tests/generated/architecture.py", "src/site/content/with-what/architecture.md"]


def test_the_committed_generated_files_are_whole():
    # act / assert
    assert cli.whole_files(GENERATED) == 0


@pytest.mark.parametrize("text", [
    "",
    "\n\n",
    "\n# Generated by firn, do not edit outside protected regions. id=[ArtifactSchema:,0123abcd]\n",
    "<!-- Generated by firn, do not edit outside protected regions. id=[Docs:,0123abcd] -->\n",
])
def test_a_file_holding_nothing_but_the_id_line_is_refused(text, tmp_path, monkeypatch, capsys):
    # arrange
    monkeypatch.setattr(cli, "ROOT", tmp_path)
    (tmp_path / "x.py").write_text(text, encoding="utf-8")

    # act
    rc = cli.whole_files(["x.py"])

    # assert
    assert rc == 1
    assert "x.py holds nothing but firn's id line" in capsys.readouterr().err


@pytest.mark.parametrize("text", [
    "# Generated by firn, do not edit. Edits are lost.\n# Generated by firn, do not edit outside protected "
    "regions. id=[ArtifactSchema:,0123abcd]\n",
    "<!-- a header comment -->\n<!-- Generated by firn, do not edit outside protected regions. "
    "id=[Docs:,0123abcd] -->\n",
    "# GENERATED from x.firn by `./simplon.sh build model`. Do not edit.\n\n# Generated by firn, id=[A:,01]\n",
])
def test_a_file_holding_only_header_comments_and_the_id_line_is_refused(text, tmp_path, monkeypatch, capsys):
    # arrange: a partial write that kept the generated header comments is no more whole than an empty file
    monkeypatch.setattr(cli, "ROOT", tmp_path)
    (tmp_path / "x.py").write_text(text, encoding="utf-8")

    # act
    rc = cli.whole_files(["x.py"])

    # assert
    assert rc == 1
    assert "x.py holds nothing but" in capsys.readouterr().err


def test_a_missing_file_is_refused_by_name(tmp_path, monkeypatch, capsys):
    # arrange
    monkeypatch.setattr(cli, "ROOT", tmp_path)

    # act
    rc = cli.whole_files(["gone.py"])

    # assert
    assert rc == 1
    assert "no such file: gone.py" in capsys.readouterr().err


def test_no_files_is_rc_1_not_a_silent_pass(capsys):
    # act / assert: a guard given nothing has checked nothing
    assert cli.whole_files([]) == 1
    assert "no files given" in capsys.readouterr().err


def test_build_model_runs_the_guard_between_gen_and_mode():
    # arrange
    import yaml
    build = yaml.safe_load((ROOT / "simplon.yaml").read_text())["ci"]["build"]["commands"]

    # act
    order = build["model"]["depends_on"]

    # assert: after gen (what it checks) and before mode (which would report done)
    assert order == ["model-guard", "model-gen", "model-whole", "model-mode"]
    assert build["model-whole"]["with"]["files"] == build["model-mode"]["with"]["files"]
