@pytest.mark.parametrize("text", [
    "",
    "\n\n",
    "\n# Generated by firn, do not edit outside protected regions. id=[ArtifactSchema:,0123abcd]\n",
    "<!-- Generated by firn, do not edit outside protected regions. id=[Docs:,0123abcd] -->\n",
    "# Generated by firn, do not edit. Edits are lost.\n# Generated by firn, do not edit outside protected "
    "regions. id=[ArtifactSchema:,0123abcd]\n",
    "<!-- a header comment -->\n<!-- Generated by firn, do not edit outside protected regions. "
    "id=[Docs:,0123abcd] -->\n",
    "# GENERATED from x.firn by `./simplon.sh build model`. Do not edit.\n\n# Generated by firn, id=[A:,01]\n",
])
def test_a_file_holding_nothing_but_the_id_line_and_header_comments_is_rc_1(text, tmp_path, capsys):
    # arrange: what a template error or a partial write leaves (si#344 B1, B2)
    _file(tmp_path, "x.py", text)

    # act
    rc = firngen.verdict(0, _out(written=["x.py"]), tmp_path)

    # assert
    assert rc == 1
    assert "x.py holds nothing but" in capsys.readouterr().err


def test_a_markdown_heading_is_content_not_a_header_comment(tmp_path):
    # arrange
    _file(tmp_path, "x.md", "# Kinds\n<!-- Generated by firn, do not edit. id=[Docs:,01] -->\n")

    # act / assert
    assert firngen.verdict(0, _out(written=["x.md"]), tmp_path) == 0


def test_build_model_is_the_guard_then_build_model_on_simplons_own_project():
    # arrange
    build = yaml.safe_load((ROOT / "simplon.yaml").read_text())["ci"]["build"]["commands"]

    # act
    order, gen = build["model"]["depends_on"], build["model-gen"]

    # assert: the region guard before gen; wholeness and modes are build:model's own, from firn's report
    assert order == ["model-guard", "model-gen"]
    assert gen["task"] == "build:model" and gen["with"]["cwd"] == "src"


@needs_docker
def test_a_renamed_task_is_refused_against_the_real_firn(tmp_path):
    # arrange: simplon's own project, then one catalogue instance renamed - firn keeps the old class file
    # with rc 0 (W301, measured)
    from firnrun import firn_rc
    project = tmp_path / "src"
    shutil.copytree(SRC / "firn", project / "firn")
    shutil.copy(SRC / "firn.toml", project / "firn.toml")
    shutil.copytree(SRC / "simplon", project / "simplon", ignore=shutil.ignore_patterns("__pycache__"))
    (project / "site" / "content" / "with-what").mkdir(parents=True)
    (project / "tests" / "generated").mkdir(parents=True)
    shutil.rmtree(project / "firn" / "model" / "product")   # its commands reference the instance by name
    tasks = project / "firn" / "model" / "simplon" / "catalogue" / "tasks.firn"
    tasks.write_text(tasks.read_text().replace("vcs_push typeOf", "vcs_pushed typeOf", 1))

    # act
    rc, out = firn_rc(tmp_path, "gen", "--format=json", cwd="src")

    # assert
    assert rc == 0                                         # firn alone calls it fine
    assert firngen.verdict(rc, out, project) == 1          # build:model does not
