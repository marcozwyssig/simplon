def test_a_deleted_file_is_rc_1_naming_it(tmp_path, capsys):
    # arrange: an empty selector deletes a generated file with rc 0 and no diagnostic (firn#966; measured on
    # v0.1.0 in the 4b review: a template taken out of firn.toml, `deleted: [artifactschema.py]`, rc 0)
    _file(tmp_path, "a.py")

