"""`support claude-md`: the central CLAUDE.md, and the product's own region kept (si#525).

Every product developed with Claude Code needs the same working agreements, and before si#525 each one
wrote them again (netctl, biz-cockpit and agile-cockpit each kept a CLAUDE.md of its own, 5-28 KB). The
central part is now the kernel's - `templates/CLAUDE.md.j2`, a synthesis of all four files Marco reviewed
on 2026-10-23 - and travels with the simplon pin, so a kernel bump brings a change to it as a diff in
review, never silently.

THE PRODUCT'S REGION IS NEVER LOST. It sits between two markers and is copied byte for byte, line endings
included. On the first run over a CLAUDE.md written before the markers, the WHOLE existing file becomes the
region: duplicates are the product's to remove afterwards, but nothing it wrote disappears. Markers that
are duplicated, out of order or half missing are refused by name and the file is left alone - a guess
there would be the silent rewrite this command exists to rule out.

`.claude/settings.json` is the native half of the plugin declaration: Claude Code offers the plugins in
`enabledPlugins` to anyone who opens the repository. It is written from the same effective set, so the two
halves cannot drift, and only the two keys this command owns are touched.

ONLY THIS COMMAND WRITES THEM. `support install` and the launcher never do: a file in the tree changes only
on a command a person ran.
"""
from __future__ import annotations

import json
from importlib import resources
from pathlib import Path

from simplon.kernel import log
from simplon.manifest import context
from simplon.tasks import claudeplugins

BEGIN = "<!-- Begin product region: keep this text on regeneration -->"
END = "<!-- End product region -->"

#: The template's own sentence, which only a CLAUDE.md this command wrote carries above its markers. A file
#: without it that holds the markers anyway - documenting the mechanism in a code block, say - is a file the
#: kernel did not write, and trusting its markers would drop everything outside them (final review).
_WRITTEN_BY_US = "This central part is generated by the Simplon delivery kernel"

#: The two `.claude/settings.json` keys this command owns; every other key is the product's.
_OWNED = ("enabledPlugins", "extraKnownMarketplaces")


def render(product: str, launcher: str, region: str) -> str:
    """The whole CLAUDE.md: the central part for `product`, then `region` between the markers."""
    central = (resources.files("simplon") / "templates" / "CLAUDE.md.j2").read_text(encoding="utf-8")
    central = central.replace("{{ product }}", product).replace("{{ launcher }}", launcher)
    return f"{central}{BEGIN}\n{region}{END}\n"


def region_of(text: str, source: str) -> str:
    """The product's region of an existing CLAUDE.md; the whole file when it has no markers yet.

    A first-generation region gets a final newline if it lacked one, so the END marker starts a line of
    its own; from then on the region is returned exactly as written.
    """
    begins, ends = text.count(BEGIN), text.count(END)
    if begins == 0 and ends == 0:
        return text if not text or text.endswith("\n") else text + "\n"
    if begins != 1 or ends != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError(f"{source}: the product region's markers are broken ({begins} begin marker(s), "
                         f"{ends} end marker(s), in that order: {BEGIN!r} ... {END!r}). Repair them by hand; "
                         f"nothing was written")
    if _WRITTEN_BY_US not in text[:text.index(BEGIN)]:
        raise ValueError(f"{source}: holds the product region's markers, but `support claude-md` did not write "
                         f"it (the central part's first paragraph is missing), so the text outside them would "
                         f"be lost. Move them out of the file, or wrap it between them, then run again; "
                         f"nothing was written")
    if text[text.index(END) + len(END):].strip("\r\n"):
        raise ValueError(f"{source}: there is text after the end marker {END!r}, which regeneration would "
                         f"drop. Move it into the region above the marker; nothing was written")
    start = text.index(BEGIN) + len(BEGIN)
    if text.startswith("\r\n", start):
        start += 2
    elif text.startswith("\n", start):
        start += 1
    return text[start:text.index(END)]


def settings(existing: dict[str, object], eff: claudeplugins.Effective) -> dict[str, object]:
    """`existing` with `enabledPlugins` and `extraKnownMarketplaces` set to the effective set.

    Key order is kept, and a key the file did not have goes at the end. The built-in marketplace needs no
    `extraKnownMarketplaces` entry: Claude Code's own schema exempts it.
    """
    out = dict(existing)
    out["enabledPlugins"] = {plugin: True for plugin in eff.plugins}
    extra: dict[str, object] = {}
    for market in eff.markets:
        if market.name == claudeplugins.BUILTIN_MARKETPLACE:
            continue
        source: dict[str, str] = {"source": "github", "repo": market.repo}
        if market.ref:
            source["ref"] = market.ref
        extra[market.name] = {"source": source}
    if extra:
        out["extraKnownMarketplaces"] = extra
    else:
        out.pop("extraKnownMarketplaces", None)
    return out


def _read(path: Path) -> str:
    """The file's text with its line endings untouched (no universal-newline translation)."""
    return path.read_bytes().decode("utf-8") if path.exists() else ""


def generate(check: bool = False) -> int:
    """Write (or, with `check`, compare) CLAUDE.md and `.claude/settings.json`; 1 on drift or a refusal."""
    ctx = context.current()
    try:
        eff = claudeplugins.effective(ctx.manifest_data(), source=str(ctx.manifest_path))
    except ValueError as exc:
        log.error(str(exc))
        return 1
    if eff is None:
        log.info("Claude support is off: 'claude' is not in toolchains:, so there is no CLAUDE.md to write")
        return 0
    root = Path(ctx.root)
    md_path, settings_path = root / "CLAUDE.md", root / ".claude" / "settings.json"
    try:
        region = region_of(_read(md_path), str(md_path))
    except ValueError as exc:
        log.error(str(exc))
        return 1
    try:
        current_settings = json.loads(_read(settings_path) or "{}")
    except ValueError as exc:
        current_settings = exc
    if not isinstance(current_settings, dict):
        log.error(f"{settings_path}: not a JSON object ({current_settings}); repair it by hand, nothing "
                  f"was written")
        return 1
    wanted = {
        md_path: render(ctx.name, f"./{ctx.name}.sh", region),
        settings_path: json.dumps(settings(current_settings, eff), indent=2) + "\n",
    }
    drift = [path for path, text in wanted.items() if _read(path) != text]
    if check:
        for path in drift:
            log.error(f"{path.relative_to(root)} is not what `support claude-md` writes; run it and commit "
                      f"the result")
        return 1 if drift else 0
    for path in drift:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(wanted[path].encode("utf-8"))
        log.ok(f"wrote {path.relative_to(root)}")
    if not drift:
        log.ok("CLAUDE.md and .claude/settings.json are current; nothing to do")
    return 0


def claude_md_cmd(check: bool = False) -> int:
    """Write this product's CLAUDE.md (simplon's central part, then the product's own region) and the
    `enabledPlugins` of `.claude/settings.json` from the `claude` toolchain; `--check` reports drift and
    writes nothing."""
    return generate(check=check)
